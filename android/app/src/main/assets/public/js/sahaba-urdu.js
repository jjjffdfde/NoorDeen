function applySahabaLanguage(lang) {
  if (typeof document === 'undefined') return;
  const cards = document.querySelectorAll('.sahaba-card');
  if (!cards || cards.length === 0) return;

  cards.forEach(card => {
    const id = card.getAttribute('id');
    if (!id) return;

    // Snapshot English card state on first load
    if (!card.dataset.enHtml) {
      card.dataset.enHtml = card.innerHTML;
    }

    if (lang === 'ur') {
      const h2 = card.querySelector('h2');
      const enTitle = card.dataset.enTitle || (h2 ? h2.textContent.trim() : '');
      if (!card.dataset.enTitle) card.dataset.enTitle = enTitle;

      const urduData = getUrduSahabaMonograph(id, enTitle);

      // Scoped Urdu translation without touching sacred Arabic scripture
      if (h2) {
        h2.textContent = urduData.title;
        h2.style.fontFamily = 'var(--font-urdu)';
      }

      const kunyaEl = card.querySelector('div[style*="font-size: 0.9rem"]');
      if (kunyaEl && !card.dataset.enKunya) {
        card.dataset.enKunya = kunyaEl.textContent;
        kunyaEl.textContent = urduData.kunya;
        kunyaEl.style.fontFamily = 'var(--font-urdu)';
      } else if (kunyaEl) {
        kunyaEl.textContent = urduData.kunya;
      }

      // Update paragraphs inside card
      const paras = card.querySelectorAll('p[style*="line-height"]');
      if (paras && paras.length > 0 && urduData.paragraphs) {
        urduData.paragraphs.forEach((uText, idx) => {
          if (paras[idx]) {
            if (!paras[idx].dataset.enText) paras[idx].dataset.enText = paras[idx].textContent;
            paras[idx].textContent = uText;
            paras[idx].style.direction = 'rtl';
            paras[idx].style.textAlign = 'right';
            paras[idx].style.fontFamily = 'var(--font-urdu)';
            paras[idx].style.lineHeight = '2.2';
          }
        });
      }

      // Quote
      const bq = card.querySelector('blockquote');
      if (bq && urduData.quote) {
        if (!bq.dataset.enQuote) bq.dataset.enQuote = bq.textContent;
        bq.textContent = urduData.quote;
        bq.style.direction = 'rtl';
        bq.style.textAlign = 'right';
        bq.style.fontFamily = 'var(--font-urdu)';
      }

      card.classList.add('urdu-content-block');
    } else {
      // Restore English with 100% fidelity
      if (card.dataset.enHtml) {
        card.innerHTML = card.dataset.enHtml;
        card.classList.remove('urdu-content-block');
      }
    }
  });
}

